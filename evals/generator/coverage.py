"""COVERAGE.md: how many documents carry each tag and field, from the truth files."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

from evals.truth import load_type


def _truths(dataset: Path) -> list[dict[str, Any]]:
    return [json.loads(p.read_text(encoding="utf-8"))
            for p in sorted(dataset.glob("**/*.truth.json"))]


def field_stats(truths: list[dict[str, Any]], type_name: str) -> list[tuple[str, str, bool, int, int]]:
    """(name, type, required, present, null) per field; table columns are counted per row."""
    docs = [t for t in truths if t["expectedType"] == type_name]
    out = []
    for f in load_type(type_name)["fields"]:
        values = [d["fields"].get(f["key"]) for d in docs]
        if f["type"] == "table":
            present = sum(1 for v in values if v)
            out.append((f["key"], "table", bool(f.get("required")), present, len(docs) - present))
            rows = [r for v in values if v for r in v]
            for c in f["columns"]:
                have = sum(1 for r in rows if r.get(c["key"]) is not None)
                out.append((f"{f['key']}.{c['key']} (rows)", c["type"], False, have, len(rows) - have))
        else:
            present = sum(1 for v in values if v is not None)
            out.append((f["key"], f["type"], bool(f.get("required")), present, len(docs) - present))
    return out


def render(dataset: Path) -> str:
    truths = _truths(dataset)
    types = Counter(t["expectedType"] or "none (distractor)" for t in truths)
    tags = Counter(tag for t in truths for tag in t["tags"])
    lines = ["# Dataset coverage", "",
             "Generated by `uv run python -m generator coverage` from the truth files. Do not edit.",
             "", f"{len(truths)} documents.", "", "## Documents per type", "",
             "| Type | Documents |", "| --- | ---: |"]
    lines += [f"| {k} | {v} |" for k, v in sorted(types.items())]
    lines += ["", "## Documents per tag", "", "| Tag | Documents |", "| --- | ---: |"]
    lines += [f"| {k} | {v} |" for k, v in sorted(tags.items())]
    for name in ("invoice", "receipt"):
        lines += ["", f"## Fields: {name}", "",
                  "Present = value is not null (a table is present when it has rows); null = the "
                  "document does not have it. Table columns count rows.", "",
                  "| Field | Type | Required | Present | Null |", "| --- | --- | --- | ---: | ---: |"]
        lines += [f"| {n} | {ty} | {'yes' if req else 'no'} | {p} | {z} |"
                  for n, ty, req, p, z in field_stats(truths, name)]
    return "\n".join(lines) + "\n"


def write_coverage(dataset: Path) -> Path:
    path = dataset / "COVERAGE.md"
    path.write_bytes(render(dataset).encode("utf-8"))
    return path
